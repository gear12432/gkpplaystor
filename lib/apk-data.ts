export function getAppBySlug(slug: string): ApkItem | undefined {
  return APK_ITEMS.find((item) => item.slug === slug);
}

export function getAppsByCategory(categoryName: string): ApkItem[] {
  const normalized = categoryName.toLowerCase();
  return APK_ITEMS.filter(
    (item) =>
      item.category.toLowerCase() === normalized ||
      CATEGORIES.find((c) => c.slug === normalized)?.name === item.category
  );
}
